# Esta función calcula el área de un rectángulo multiplicando su base y altura
def area_rectangulo(base, altura):
    return base * altura

# Esta función calcula el área de un triángulo multiplicando su base y altura y dividiendo el resultado entre 2
def area_triangulo(base, altura):
    return (base * altura) / 2

# Esta función calcula el área de un círculo multiplicando el valor de pi por el radio al cuadrado
def area_circulo(radio):
    return 3.14 * radio**2